using System;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace Capstone.Game.CreatureSystem.Editor {
    /// <summary>Explicit scene authoring only; never runs from an import/update hook.</summary>
    public static class EnemyAiSetup {
        public const string Root=UISystem.QaArtifactPaths.Root+"enemy-ai-retaliation-skills-2026-11-16/";
        public static string OriginalHash(){using(var sha=SHA256.Create())return BitConverter.ToString(sha.ComputeHash(File.ReadAllBytes("Assets/Scenes/DemoScene.unity"))).Replace("-","");}
        [MenuItem("Tools/Capstone/PvE/8. Apply retaliation and skill AI (DemoScene 1)")]
        public static void Apply(){
            var scene=EditorSceneManager.GetActiveScene();
            if(EditorApplication.isPlayingOrWillChangePlaymode||scene.path!="Assets/Scenes/DemoScene 1.unity")throw new InvalidOperationException("Dừng Play và mở DemoScene 1.");
            string hash=OriginalHash();Directory.CreateDirectory(Root+"backups");
            string backup=Root+"backups/before-ai-authoring-"+DateTime.UtcNow.ToString("yyyyMMdd-HHmmss")+".unity";
            if(!EditorSceneManager.SaveScene(scene,backup,true))throw new IOException("Không tạo được bản sao scene trước khi gắn AI.");
            File.AppendAllText(Root+"created-paths.txt",backup+"\n");
            int hurtboxes=0;
            foreach(string group in new[]{"Dragons","Bats"})foreach(string guid in AssetDatabase.FindAssets("t:Prefab",new[]{"Assets/Game/CreatureSystem/Runtime/"+group+"/OwnedPet"})){
                string assetPath=AssetDatabase.GUIDToAssetPath(guid),original=Root+"backups/"+Path.GetFileName(assetPath)+".before-hurtbox";
                string source=File.ReadAllText(assetPath);bool authoredHurtbox=source.Contains("CapsuleCollider:");
                if(authoredHurtbox){if(File.Exists(original))KeepOnlyHurtbox(assetPath,File.ReadAllText(original),source);continue;}
                var contents=PrefabUtility.LoadPrefabContents(assetPath);
                try{
                    if(contents.GetComponent<CreatureCombatant>()==null)continue;
                    if(!File.Exists(original)){File.Copy(assetPath,original);File.AppendAllText(Root+"created-paths.txt",original+"\n");}
                    var hurtbox=contents.GetComponent<CapsuleCollider>()??contents.AddComponent<CapsuleCollider>();hurtbox.isTrigger=true;hurtbox.radius=.35f;hurtbox.height=1.2f;hurtbox.center=Vector3.up*.65f;
                    PrefabUtility.SaveAsPrefabAsset(contents,assetPath);
                    KeepOnlyHurtbox(assetPath,source,File.ReadAllText(assetPath));hurtboxes++;
                }finally{PrefabUtility.UnloadPrefabContents(contents);}
            }
            var roots=scene.GetRootGameObjects();
            var enemies=roots.SelectMany(r=>r.GetComponentsInChildren<BasicCreatureEnemy>(true)).Where(b=>b.enabled&&b.GetComponent<DummyEnemy>() is var h&&h!=null&&!h.IsTrainingDummy&&!h.IsBoss).ToArray();
            var owners=roots.SelectMany(r=>r.GetComponentsInChildren<EncounterSpawnPoint>(true)).ToArray();
            foreach(var brain in enemies){
                Undo.RecordObject(brain,"Retaliation and skill AI");brain.useSkills=true;brain.skillChance=.35f;brain.decisionInterval=.3f;brain.pathInterval=.25f;brain.searchSeconds=2;
                EditorUtility.SetDirty(brain);PrefabUtility.RecordPrefabInstancePropertyModifications(brain);
                var owner=owners.FirstOrDefault(o=>o.initialActor==brain.GetComponent<DummyEnemy>());
                if(owner!=null){Undo.RecordObject(owner,"Persist respawn AI settings");owner.settings.Read(brain);EditorUtility.SetDirty(owner);}
            }
            EditorSceneManager.MarkSceneDirty(scene);if(!EditorSceneManager.SaveScene(scene))throw new IOException("Không lưu được DemoScene 1.");
            if(OriginalHash()!=hash)throw new InvalidOperationException("Hash DemoScene gốc đã đổi.");
            string path=Root+"authoring.txt";File.WriteAllText(path,"APPLIED retaliation-only AI with shared skills\nactors="+enemies.Length+"\nowned runtime hurtboxes added="+hurtboxes+"\noriginal="+hash+"\nNo source model/controller, save or stat formula changes.");File.AppendAllText(Root+"created-paths.txt",path+"\n");
        }
        // OnValidate refreshes cached skill display data while loading a prefab. Preserve
        // its original serialized data; retain only the collider generated by the Editor.
        static void KeepOnlyHurtbox(string path,string original,string authored){
            if(original.Contains("CapsuleCollider:"))return;
            var block=Regex.Match(authored,@"(?ms)^--- !u!136 &(\d+)\r?\nCapsuleCollider:.*?(?=^--- !u!|\z)");
            if(!block.Success)throw new InvalidOperationException("Không tìm thấy CapsuleCollider do Editor tạo: "+path);
            var layer=new Regex(@"^  m_Layer:",RegexOptions.Multiline);
            string result=layer.Replace(original,"  - component: {fileID: "+block.Groups[1].Value+"}\n  m_Layer:",1).TrimEnd()+"\n"+block.Value.TrimEnd()+"\n";
            File.WriteAllText(path,result);AssetDatabase.ImportAsset(path,ImportAssetOptions.ForceUpdate);
        }
    }
}
